const homeScreen = document.getElementById("home-screen");
const levelScreenExt = document.getElementById("level-screen");
const quizScreenExt = document.getElementById("quiz-screen");
const resultScreenExt = document.getElementById("result-screen");
const readingsScreen = document.getElementById("readings-screen");
const readerScreen = document.getElementById("reader-screen");
const navRouteButtons = [...document.querySelectorAll("[data-route]")];
const mainNavButtonsExt = [...document.querySelectorAll(".main-nav .nav-link")];
const readingGrid = document.getElementById("reading-grid");
const filterButtons = [...document.querySelectorAll("[data-reading-filter]")];
let readingFilter = "all";
let currentStoryId = null;

function hideExtendedScreens() {
  [homeScreen, levelScreenExt, quizScreenExt, resultScreenExt, readingsScreen, readerScreen].forEach((screen) => screen.classList.add("hidden"));
}

function updateMainNav(route) {
  mainNavButtonsExt.forEach((button) => button.classList.toggle("active", button.dataset.route === route));
}

function navigateExtended(route) {
  hideExtendedScreens();
  if (route === "quiz") {
    levelScreenExt.classList.remove("hidden");
    updateMainNav("quiz");
  } else if (route === "readings") {
    renderReadingCards();
    readingsScreen.classList.remove("hidden");
    updateMainNav("readings");
  } else {
    homeScreen.classList.remove("hidden");
    updateMainNav("home");
  }
  window.scrollTo({ top: 0, behavior: "smooth" });
}

navRouteButtons.forEach((button) => button.addEventListener("click", () => navigateExtended(button.dataset.route)));

function isStoryRead(storyId) {
  try { return localStorage.getItem(`vae-read-${storyId}`) === "yes"; } catch { return false; }
}

function renderReadingCards() {
  readingGrid.innerHTML = "";
  Object.entries(readingData)
    .filter(([, story]) => readingFilter === "all" || story.level === readingFilter)
    .forEach(([id, story]) => {
      const card = document.createElement("article");
      card.className = "reading-card";
      card.innerHTML = `
        <div class="reading-card-top"><span class="story-level">${story.level}</span><span class="story-time">${story.time} de leitura</span></div>
        <h2>${story.title}</h2>
        <p>${story.description}</p>
        <div class="reading-card-footer">
          <button class="primary-button" type="button" data-open-story="${id}">Leer ahora</button>
          <span class="read-status">${isStoryRead(id) ? "✓ Leída" : ""}</span>
        </div>`;
      readingGrid.appendChild(card);
    });

  readingGrid.querySelectorAll("[data-open-story]").forEach((button) => {
    button.addEventListener("click", () => openStory(button.dataset.openStory));
  });
}

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    readingFilter = button.dataset.readingFilter;
    filterButtons.forEach((item) => item.classList.toggle("active", item === button));
    renderReadingCards();
  });
});

const readerTitle = document.getElementById("reader-title");
const storyMeta = document.getElementById("story-meta");
const storyIntro = document.getElementById("story-intro");
const storyBody = document.getElementById("story-body");
const glossaryList = document.getElementById("glossary-list");
const comprehensionForm = document.getElementById("comprehension-form");
const comprehensionResult = document.getElementById("comprehension-result");
const savedNote = document.getElementById("saved-note");
const markReadButton = document.getElementById("mark-read-button");

function openStory(storyId) {
  currentStoryId = storyId;
  const story = readingData[storyId];
  hideExtendedScreens();
  readerScreen.classList.remove("hidden");
  updateMainNav("readings");
  readerTitle.textContent = story.title;
  storyMeta.innerHTML = `<span>${story.level}</span><span>${story.time}</span><span>${story.theme}</span>`;
  storyIntro.textContent = story.intro;
  storyBody.innerHTML = story.paragraphs.map((paragraph) => `<p>${paragraph}</p>`).join("");
  glossaryList.innerHTML = story.glossary.map(([term, meaning]) => `<div><dt>${term}</dt><dd>${meaning}</dd></div>`).join("");
  savedNote.textContent = isStoryRead(storyId) ? "✓ Esta leitura já está marcada como concluída." : "";
  markReadButton.textContent = isStoryRead(storyId) ? "Leída ✓" : "Marcar como leída";
  renderComprehension(story);
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function renderComprehension(story) {
  comprehensionResult.className = "comprehension-result hidden";
  comprehensionResult.textContent = "";
  comprehensionForm.innerHTML = story.comprehension.map((item, qIndex) => {
    const options = item.options.map((option, oIndex) => `<label class="comp-option"><input type="radio" name="comp-${qIndex}" value="${oIndex}" /><span>${option}</span></label>`).join("");
    return `<fieldset class="comp-question"><legend>${qIndex + 1}. ${item.q}</legend>${options}</fieldset>`;
  }).join("");
}

document.getElementById("reader-back-button").addEventListener("click", () => navigateExtended("readings"));
markReadButton.addEventListener("click", () => {
  if (!currentStoryId) return;
  try { localStorage.setItem(`vae-read-${currentStoryId}`, "yes"); } catch { /* Storage may be unavailable. */ }
  markReadButton.textContent = "Leída ✓";
  savedNote.textContent = "✓ Progresso salvo neste navegador.";
});

document.getElementById("check-comprehension-button").addEventListener("click", () => {
  if (!currentStoryId) return;
  const story = readingData[currentStoryId];
  let correctCount = 0;
  let answeredCount = 0;
  story.comprehension.forEach((item, index) => {
    const selected = comprehensionForm.querySelector(`input[name="comp-${index}"]:checked`);
    if (selected) {
      answeredCount += 1;
      if (Number(selected.value) === item.correct) correctCount += 1;
    }
  });

  comprehensionResult.classList.remove("hidden", "good", "needs-work");
  if (answeredCount < story.comprehension.length) {
    comprehensionResult.classList.add("needs-work");
    comprehensionResult.textContent = `Responda às ${story.comprehension.length} perguntas antes de corrigir. Você respondeu ${answeredCount}.`;
    return;
  }

  const ratio = correctCount / story.comprehension.length;
  comprehensionResult.classList.add(ratio >= 0.75 ? "good" : "needs-work");
  comprehensionResult.textContent = ratio === 1
    ? `¡Excelente! ${correctCount}/${story.comprehension.length}. Você compreendeu muito bem a leitura.`
    : `${correctCount}/${story.comprehension.length} respostas corretas. ${ratio >= 0.75 ? "¡Muy bien!" : "Revise o texto e tente novamente."}`;
});

renderReadingCards();
navigateExtended("home");
